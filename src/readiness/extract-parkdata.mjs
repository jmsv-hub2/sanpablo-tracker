// Dev-time generator: reads ../App.jsx (read-only) and emits parkdata.js with
// the table → SCB → inverter mapping the readiness demo needs. Run with:
//   node src/readiness/extract-parkdata.mjs
// Regenerate whenever the arrays in App.jsx change. Never edits App.jsx.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(here, '..', 'App.jsx'), 'utf8');

const arr = (name) => {
  const m = src.match(new RegExp('const ' + name + '\\s*=\\s*\\[([^\\]]*)\\]'));
  if (!m) throw new Error('array not found in App.jsx: ' + name);
  return m[1].split(',').map((s) => s.trim());
};

const MV = arr('_MV').map(Number);
const ZN = arr('_ZN').map(Number);
const N = arr('_N').map(Number);
const SCBIDX = arr('_SCBIDX').map(Number);
const SCB_IDS = arr('SCB_IDS').map((s) => s.replace(/^"|"$/g, ''));

if (new Set([MV.length, ZN.length, N.length, SCBIDX.length]).size !== 1)
  throw new Error('array length mismatch');

const bcMatch = src.match(/const BC=\{([^}]*)\}/);
if (!bcMatch) throw new Error('BC not found');

const out = `// GENERATED by extract-parkdata.mjs from src/App.jsx — do not edit by hand.
// ${MV.length} tables · ${SCB_IDS.length} SCBs.
export const BC = {${bcMatch[1]}};
export const SCB_IDS = ${JSON.stringify(SCB_IDS)};
const _MV = ${JSON.stringify(MV)};
const _ZN = ${JSON.stringify(ZN)};
const _N = ${JSON.stringify(N)};
const _SCBIDX = ${JSON.stringify(SCBIDX)};
export const TABLES = _ZN.map((z, i) => ({
  id: \`C\${z}-\${_N[i]}\`,
  m: _MV[i],
  scb: _SCBIDX[i] >= 0 ? SCB_IDS[_SCBIDX[i]] : null,
}));
`;
fs.writeFileSync(path.join(here, 'parkdata.js'), out);
console.log('parkdata.js written:', MV.length, 'tables,', SCB_IDS.length, 'SCBs');
